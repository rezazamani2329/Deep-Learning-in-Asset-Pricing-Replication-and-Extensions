def monthly_sharpe(x):
    x = pd.Series(x).dropna().astype(float)

    if len(x) < 2:
        return np.nan

    sd = x.std(ddof=1)

    if sd == 0:
        return np.nan

    return x.mean() / sd


def fit_tangency_weights(
    df,
    factor_cols,
):
    X = df[
        factor_cols
    ].to_numpy(dtype=float)

    mu = X.mean(axis=0)

    cov = np.cov(
        X,
        rowvar=False,
        ddof=1,
    )

    w = (
        np.linalg.pinv(
            cov,
            rcond=1e-12,
        )
        @ mu
    )

    gross = np.abs(w).sum()

    if gross <= 0:
        raise ValueError(
            "Tangency portfolio has zero gross exposure."
        )

    return w / gross


def build_fixed_weight_factor(
    df,
    factor_cols,
    weights,
    model_name,
):
    out = df[
        ["date", *factor_cols]
    ].copy()

    out["factor_return"] = (
        out[factor_cols]
        .to_numpy(dtype=float)
        @ weights
    )

    out["model"] = model_name
    out["split"] = (
        out["date"]
        .map(assign_split)
    )

    return out[
        [
            "date",
            "split",
            "model",
            "factor_return",
        ]
    ]



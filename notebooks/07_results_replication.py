def monthly_sharpe(r):
    r = pd.Series(r).dropna().astype(float)

    vol = r.std(ddof=1)

    if vol == 0 or np.isnan(vol):
        return np.nan

    return r.mean() / vol


def max_negative_streak(returns):
    streak = 0
    best = 0

    for value in returns:
        if value < 0:
            streak += 1
            best = max(best, streak)
        else:
            streak = 0

    return best



def load_french_monthly_zip(
    url,
    cache_path,
):
    if cache_path.exists():
        out = pd.read_csv(
            cache_path,
            parse_dates=["date"],
        )
        print(
            "Loaded cached:",
            cache_path.name,
        )
        return out

    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "Mozilla/5.0"
        },
    )

    with urllib.request.urlopen(
        request,
        timeout=60,
    ) as response:
        content = response.read()

    with zipfile.ZipFile(
        BytesIO(content)
    ) as zf:

        csv_files = [
            name
            for name in zf.namelist()
            if name.lower().endswith(".csv")
        ]

        if not csv_files:
            raise RuntimeError(
                "No CSV found inside French zip file."
            )

        text = (
            zf.read(csv_files[0])
            .decode(
                "latin1",
                errors="replace",
            )
        )

    lines = text.splitlines()

    header_idx = next(
        i
        for i, line in enumerate(lines)
        if (
            "Mkt-RF" in line
            and "SMB" in line
        )
    )

    header = [
        x.strip()
        for x in lines[
            header_idx
        ].split(",")
    ]

    if header[0] == "":
        header[0] = "yyyymm"

    rows = []

    for line in lines[
        header_idx + 1:
    ]:
        parts = [
            x.strip()
            for x in line.split(",")
        ]

        if (
            not parts
            or not re.fullmatch(
                r"\d{6}",
                parts[0],
            )
        ):
            break

        if len(parts) == len(header):
            rows.append(parts)

    df = pd.DataFrame(
        rows,
        columns=header,
    )

    df["date"] = pd.to_datetime(
        df["yyyymm"],
        format="%Y%m",
    )

    factor_cols = [
        c
        for c in df.columns
        if c not in {
            "yyyymm",
            "date",
        }
    ]

    for col in factor_cols:
        df[col] = (
            pd.to_numeric(
                df[col],
                errors="coerce",
            )
            / 100.0
        )

    df = (
        df[
            ["date", *factor_cols]
        ]
        .dropna()
        .sort_values("date")
        .reset_index(drop=True)
    )

    df.to_csv(
        cache_path,
        index=False,
    )

    print(
        "Downloaded and cached:",
        cache_path.name,
    )

    return df



def normalize_split_names(series):
    """
    Convert possible split labels to the common convention:
    train / validation / test
    """
    mapping = {
        "train": "train",
        "training": "train",
        "valid": "validation",
        "validation": "validation",
        "val": "validation",
        "test": "test",
        "testing": "test",
    }

    return (
        series
        .astype(str)
        .str.strip()
        .str.lower()
        .map(mapping)
    )


def find_split_column(df):
    """
    Look for common names used for the sample split.
    """
    candidates = [
        "split",
        "sample",
        "period",
        "dataset",
        "set",
    ]

    for col in candidates:
        if col in df.columns:
            return col

    return None


def standardize_performance_table(
    df,
    model_name=None,
    source_name="model",
):
    """
    Standardize performance tables produced by earlier notebooks.
    """

    out = df.copy()

    # --------------------------------------------------------
    # 1. Clean column names
    # --------------------------------------------------------

    out.columns = [
        str(c).strip()
        for c in out.columns
    ]


    # --------------------------------------------------------
    # 2. Identify / construct model column
    # --------------------------------------------------------

    if "model" not in out.columns:

        if model_name is None:
            raise ValueError(
                f"{source_name}: no model column found."
            )

        out["model"] = model_name


    # --------------------------------------------------------
    # 3. Identify split column
    # --------------------------------------------------------

    split_col = find_split_column(out)

    if split_col is not None:

        if split_col != "split":
            out = out.rename(
                columns={
                    split_col: "split"
                }
            )

        out["split"] = normalize_split_names(
            out["split"]
        )


    # --------------------------------------------------------
    # 4. Special recovery for linear table
    #
    # Code 03 has two models (LS and EN), each evaluated on
    # train / validation / test.
    # --------------------------------------------------------

    if "split" not in out.columns:
        raise ValueError(f"{source_name}: explicit split/sample column required; refusing to infer splits from row order.")
    if out["split"].isna().any():
        raise ValueError(f"{source_name}: missing or unrecognized split labels.")

    # --------------------------------------------------------
    # 5. Standardize model labels
    # --------------------------------------------------------

    out["model"] = (
        out["model"]
        .astype(str)
        .str.strip()
        .str.upper()
    )


    # --------------------------------------------------------
    # 6. Standardize common performance column names
    # --------------------------------------------------------

    rename_map = {
        "vol_monthly":
            "volatility_monthly",

        "volatility":
            "volatility_monthly",

        "min_month":
            "minimum_month",

        "minimum":
            "minimum_month",

        "max_month":
            "maximum_month",

        "maximum":
            "maximum_month",

        "positive_fraction":
            "positive_month_fraction",
    }

    out = out.rename(
        columns={
            k: v
            for k, v in rename_map.items()
            if k in out.columns
        }
    )


    # --------------------------------------------------------
    # 7. Recover monthly Sharpe if only annualized is present
    # --------------------------------------------------------

    if (
        "monthly_sharpe"
        not in out.columns
        and "annualized_sharpe"
        in out.columns
    ):

        out["monthly_sharpe"] = (
            out["annualized_sharpe"]
            / np.sqrt(12.0)
        )


    # --------------------------------------------------------
    # 8. Recover annualized Sharpe if needed
    # --------------------------------------------------------

    if (
        "annualized_sharpe"
        not in out.columns
        and "monthly_sharpe"
        in out.columns
    ):

        out["annualized_sharpe"] = (
            out["monthly_sharpe"]
            * np.sqrt(12.0)
        )


    # --------------------------------------------------------
    # 9. Harmonize months
    # --------------------------------------------------------

    if "months" not in out.columns:

        month_map = {
            "train": 240,
            "validation": 60,
            "test": 300,
        }

        out["months"] = (
            out["split"]
            .map(month_map)
        )


    # --------------------------------------------------------
    # 10. Final checks
    # --------------------------------------------------------

    expected_splits = {
        "train",
        "validation",
        "test",
    }

    found_splits = set(
        out["split"].dropna()
    )

    if found_splits != expected_splits:

        raise ValueError(
            f"{source_name}: unexpected split labels: "
            f"{found_splits}"
        )

    return out

